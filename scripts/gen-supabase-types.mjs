/**
 * Regenerates Supabase Database types from the linked remote project.
 * Usage: node scripts/gen-supabase-types.mjs
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = resolve(
  root,
  "packages/database/src/generated/database.types.ts",
);

mkdirSync(dirname(outFile), { recursive: true });

const result = spawnSync(
  "npx",
  ["supabase", "gen", "types", "typescript", "--linked"],
  {
    cwd: root,
    encoding: "utf8",
    shell: true,
  },
);

if (result.status !== 0) {
  process.stderr.write(result.stderr || result.stdout || "typegen failed\n");
  process.exit(result.status ?? 1);
}

const banner = `/**
 * AUTO-GENERATED by \`npm run db:gen-types\` (supabase gen types --linked).
 * Do not edit by hand. Domain/view models live elsewhere (e.g. packages/database/src/schemas.ts).
 */

`;

writeFileSync(outFile, banner + (result.stdout ?? ""), "utf8");
process.stdout.write(`Wrote ${outFile}\n`);
